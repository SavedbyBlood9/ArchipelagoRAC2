"""Export each disc's boot-address moves from a pinned OpenRAC checkout's release maps; no disc bytes.

Runtime facts are USA v1.01 (rac2/ntsc) addresses. OpenRAC's port/game/rac2-<disc>/release/
data_moves.tsv says how each other disc's release moved that data: this writes its boot-program
runs as src/<disc>_boot_moves.hpp, which src/disc.hpp translates through.
"""
import argparse
from pathlib import Path

DISCS = {  # disc: (C++ table name, what the header calls it)
    'pal': ('kPalBootMoves', 'PAL'),
    'ntsc2': ('kNtsc2BootMoves', 'USA v2.00'),
}

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('checkout',type=Path)
a=p.parse_args()
root=Path(__file__).resolve().parents[1]
for disc,(table,label) in DISCS.items():
    source=a.checkout/f'port/game/rac2-{disc}/release/data_moves.tsv'
    ranges=[]
    for line in source.read_text().splitlines():
        if not line.startswith('boot\t'):continue
        _,first,last,move,*_=line.split('\t')
        ranges.append((int(first,16),int(last,16),int(move,0)))
    if not ranges or any(lo>hi for lo,hi,_ in ranges):raise ValueError(f'Invalid {label} boot map')
    for left,right in zip(ranges,ranges[1:]):
        if left[1]>=right[0]:raise ValueError(f'Overlapping {label} boot ranges')
    out=root/f'src/{disc}_boot_moves.hpp'
    struct='struct BootMove { unsigned first,last; int move; };\n' if disc=='pal' else ''
    include='' if disc=='pal' else '#include "pal_boot_moves.hpp"\n'
    out.write_text('// Generated by tools/generate_disc_profiles.py from OpenRAC release/data_moves.tsv.\n'
                   '// Address facts only; no game code or disc assets.\n#pragma once\n'+include+
                   'namespace rac2ap {\n'+struct+
                   f'inline constexpr BootMove {table}[] = {{\n'+
                   ''.join(f'    {{0x{lo:08X}u,0x{hi:08X}u,{move}}},\n' for lo,hi,move in ranges)+
                   '};\n}\n',encoding='utf-8',newline='\n')
    print(len(ranges),label,'boot-address ranges exported to',out.relative_to(root))
