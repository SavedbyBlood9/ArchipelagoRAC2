"""Export PAL boot-address facts from the pinned OpenRAC release map; no disc bytes."""
import argparse
from pathlib import Path

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('checkout',type=Path)
a=p.parse_args()
source=a.checkout/'port/game/rac2-pal/release/data_moves.tsv'
ranges=[]
for line in source.read_text().splitlines():
    if not line.startswith('boot\t'):continue
    _,first,last,move,*_=line.split('\t')
    ranges.append((int(first,16),int(last,16),int(move,0)))
if not ranges or any(lo>hi for lo,hi,_ in ranges):raise ValueError('Invalid PAL boot map')
for left,right in zip(ranges,ranges[1:]):
    if left[1]>=right[0]:raise ValueError('Overlapping PAL boot ranges')
out=Path(__file__).resolve().parents[1]/'src/pal_boot_moves.hpp'
out.write_text('// Generated by tools/generate_pal_profile.py from OpenRAC release/data_moves.tsv.\n'
               '// Address facts only; no game code or disc assets.\n#pragma once\n'
               'namespace rac2ap {\nstruct BootMove { unsigned first,last; int move; };\n'
               'inline constexpr BootMove kPalBootMoves[] = {\n'+
               ''.join(f'    {{0x{lo:08X}u,0x{hi:08X}u,{move}}},\n' for lo,hi,move in ranges)+
               '};\n}\n',encoding='utf-8',newline='\n')
print(len(ranges),'PAL boot-address ranges exported')
